#!/usr/bin/env node
/**
 * Append extension questions to the three hand-maintained banks.
 *
 * The banks are the source oftruth and are edited by people, so this script is
 * careful never to rewrite existing content: it truncates at a marker it owns,
 * re-emits the extension, and leaves everything above the marker untouched. The
 * marker is an HTML comment, which every markdown renderer discards.
 *
 * Numbering continues from the last existing question, and the parser tests
 * assert the numbers are contiguous, so the emitted block must start at
 * `last + 1`.
 *
 * Usage:
 *   node scripts/append-questions.mjs --check   # report what would change
 *   node scripts/append-questions.mjs --write   # apply
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

import { CMSIP } from './lib/questions-cmsip.mjs';
import { FMRP } from './lib/questions-fmrp.mjs';
import { RES12B } from './lib/questions-res12b.mjs';
import { CMEIP } from './lib/questions-cmeip.mjs';

const MARKER = '<!-- EXTENSION QUESTIONS BELOW — generated by scripts/append-questions.mjs -->';
const WRITE = process.argv.includes('--write');

/** Roman-numeral-free letter for a 0-based index. */
const LETTERS = ['a', 'b', 'c', 'd'];

/** Escape nothing but keep backslashes intact for KaTeX. */
function clean(text) {
  return String(text).replace(/\s+/g, ' ').trim();
}

/* ------------------------------------------------------------------ CM-SIP */

/**
 * CM-SIP markup:
 *
 *   ## Chapter 1 — Overview of Derivatives
 *
 *   **42. [Single choice]** stem
 *
 *   a. option
 *   …
 *
 *   <details>
 *   <summary>Show answer</summary>
 *
 *   **Answer: a.** rationale
 *
 *   </details>
 *
 * The heading has to be a `## Chapter N — Title` line so the parser assigns the
 * chapter. Items are grouped by `c` and emitted under a fresh heading per group.
 */
function renderCmsip(items, startNumber, guideTitles) {
  const groups = new Map();
  for (const item of items) {
    if (!groups.has(item.c)) groups.set(item.c, []);
    groups.get(item.c).push(item);
  }

  const parts = [];
  let n = startNumber;
  for (const [chapter, group] of groups) {
    const title = guideTitles.get(chapter) ?? chapter;
    // Reuse the guide's own title so the parser's chapter match is exact, and
    // keep the heading at level 2 in the `Chapter N — Title` form it expects.
    const heading = /^\d+$/.test(chapter)
      ? `## Chapter ${chapter} — ${stripLeadingNumber(title)}`
      : `## Appendix ${chapter.split('-')[1]} — ${stripLeadingNumber(title)}`;
    parts.push(heading, '');

    // Items may carry `sec` (a syllabus section number such as `4.7`). Emitting it
    // as a `### <num>` subheading is what lets the parser attribute the question to
    // a syllabus row, so per-section coverage becomes measurable. A bare number is
    // enough: `parseBank` keys on the number and the guide carries the title. Items
    // without `sec` stay directly under the chapter heading, as before.
    let currentSec = null;
    for (const item of group) {
      const sec = item.sec ?? null;
      if (sec !== currentSec) {
        currentSec = sec;
        if (sec) parts.push(`### ${sec}`, '');
      }
      // Option letters are lower-case in this bank, so the answer keys are
      // normalised here: the data file uses whatever case reads naturally, but the
      // emitted markup and the parser both expect `a`..`d`.
      const keys = item.a
        .split(',')
        .map((k) => k.trim().toLowerCase())
        .filter(Boolean);
      parts.push(`**${n}. [${item.t}]** ${clean(item.q)}`, '');
      item.o.forEach((opt, i) => parts.push(`${LETTERS[i]}. ${clean(opt)}`));
      parts.push('');
      parts.push('<details>');
      parts.push('<summary>Show answer</summary>');
      parts.push('');
      const pretty =
        keys.length > 1
          ? keys.length === 2
            ? `${keys[0]} and ${keys[1]}`
            : `${keys.slice(0, -1).join(', ')} and ${keys.at(-1)}`
          : keys[0];
      parts.push(`**Answer: ${pretty}.** ${clean(item.r)}`);
      parts.push('');
      parts.push('</details>');
      parts.push('');
      n += 1;
    }
  }
  return parts.join('\n');
}

/** Drop a leading `1 `, `Appendix A — ` or similar so the title is bare. */
function stripLeadingNumber(title) {
  return String(title)
    .replace(/^Appendix\s+[A-Z]\s*[—–-]\s*/i, '')
    .replace(/^\d+[A-Z]?-\d+\s+/, '')
    .replace(/^\d+\s+/, '')
    .trim();
}

/* -------------------------------------------------------------------- FMRP */

/**
 * FMRP / RES 12B markup:
 *
 *   ## Chapter 1 - Introduction
 *
 *   ### 42. **[Original | Single choice]** [FMRP §1.2.2] stem
 *
 *   - a. option
 *   …
 *
 *   <details>
 *   <summary>Show answer</summary>
 *
 *   **Answer:** B. the correct option text
 *
 *   **Rationale:** why
 *
 *   </details>
 *
 * The answer must repeat the correct option text, which the parser uses as the
 * answer payload; a bare letter is not enough for this format.
 */
function renderHeadingStyle(items, startNumber, opts) {
  const { sourceRefFor, groupingKey, subtypeFor } = opts;
  const groups = new Map();
  for (const item of items) {
    const key = groupingKey(item);
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(item);
  }

  // The answer text is the option whose letter matches the first answer key.
  const parts = [];
  let n = startNumber;
  for (const [heading, group] of groups) {
    parts.push(heading, '');
    for (const item of group) {
      const keys = item.a.split(',').map((k) => k.trim().toUpperCase());
      const ref = sourceRefFor(item);
      // `subtypeFor` is deliberately separate from `sourceRefFor`: in the RES 12B
      // data `s` *is* the source tag, so deriving the subtype from it stamped
      // `Single choice | RES 1B §2.3` into the type field and repeated the tag. A
      // null subtype emits the bare type, which is what the other banks show.
      const subtype = subtypeFor ? subtypeFor(item) : null;
      const typeTag = subtype ? `${item.t} | ${subtype}` : item.t;
      parts.push(`### ${n}. **[${typeTag}]**${ref ? ` [${ref}]` : ''} ${clean(item.q)}`, '');
      item.o.forEach((opt, i) => {
        parts.push(`- ${LETTERS[i]}. ${clean(opt)}`);
      });
      parts.push('');

      // For a single answer, quote the correct option. For a combination answer,
      // the option list already holds the combinations, so quote that option text.
      const firstKey = keys[0];
      const correctIndex = LETTERS.indexOf(firstKey.toLowerCase());
      const correctText = correctIndex >= 0 ? clean(item.o[correctIndex]) : '';
      const answerPayload = keys.length > 1 ? keys.join(', ') : `${firstKey.toUpperCase()}. ${correctText}`;

      parts.push('<details>');
      parts.push('<summary>Show answer</summary>');
      parts.push('');
      parts.push(`**Answer:** ${answerPayload}`);
      parts.push('');
      parts.push(`**Rationale:** ${clean(item.r)}`);
      parts.push('');
      parts.push('</details>');
      parts.push('');
      n += 1;
    }
  }
  return parts.join('\n');
}

/* ------------------------------------------------------------------ driver */

/**
/**
 * FMRP source tag.
 *
 * The parser only derives a chapter from the `##` heading for the `heading`
 * bank format, so the tag is purely informative for FMRP. It is still emitted
 * because the bank's existing questions all carry one and readers use it to find
 * the relevant guide section.
 */
function fmrpSourceRef(item) {
  if (/^\d+$/.test(item.c)) return `FMRP §${item.c}`;
  if (item.c === 'appendix-A') return 'FMRP Appendix A';
  if (item.c === 'appendix-B') return 'FMRP Appendix B';
  return null;
}

/** Read the guide chapter titles so appended headings match the parser exactly. */
function guideTitles(exam) {
  const titles = new Map();
  const dir = `notes/${exam}/guide`;
  for (const name of readdirSync(dir)) {
    if (!name.endsWith('.md')) continue;
    const raw = readFileSync(`${dir}/${name}`, 'utf8');
    const fm = raw.match(/^---\n([\s\S]*?)\n---/);
    if (!fm) continue;
    const id = fm[1].match(/^id:\s*'?"?([^'"\n]+)'?"?/m)?.[1];
    const title = fm[1].match(/^title:\s*'?"?([^'"\n]+)'?"?/m)?.[1];
    if (id && title) titles.set(id, title);
  }
  return titles;
}

const JOBS = [
  {
    name: 'CM-SIP',
    file: 'notes/cmsip/CMSIP_QUESTIONS.md',
    items: CMSIP,
    render: (items, start, titles) => renderCmsip(items, start, titles),
    exam: 'cmsip',
  },
  {
    name: 'FMRP',
    file: 'notes/fmrp/FMRP_QUESTIONS.md',
    items: FMRP,
    render: (items, start, titles) =>
      renderHeadingStyle(items, start, {

        sourceRefFor: fmrpSourceRef,
        // FMRP keeps its `Original | Multiple response` subtype, which is
        // meaningful: it records whether the item was adapted from the source's
        // Appendix A or written fresh.
        subtypeFor: (item) => item.s ?? 'Single choice',
        groupingKey: (item) => {
          const title = titles.get(item.c) ?? item.c;
          if (/^appendix-/i.test(item.c)) {
            return `## Appendix ${item.c.split('-')[1]} — ${stripLeadingNumber(title)}`;
          }
          if (item.c === 'cross-chapter-exam-method') return '## Cross-chapter exam method';
          return `## Chapter ${item.c} — ${stripLeadingNumber(title)}`;
        },
      }),
    exam: 'fmrp',
  },
  {
    name: 'RES 12B',
    file: 'notes/res12b/RES12B_QUESTIONS.md',
    items: RES12B,
    render: (items, start) =>
      renderHeadingStyle(items, start, {
        sourceRefFor: (item) => item.s,
        // No subtype: `item.s` is the source tag, already emitted as the reference,
        // so repeating it in the type tag duplicated the reference and put
        // `Single choice | RES 1B §2.3` in the UI badge.
        subtypeFor: () => null,
        groupingKey: (item) => {
          // RES 12B assigns the chapter from the source tag, so a single heading is
          // enough and keeps the appended block compact.
          const part = item.s.includes('2B') ? 'RES 2B' : 'RES 1B';
          const area = item.s.includes('Appendix') ? 'Appendices' : 'Extension';
          return `## ${part} — ${area}`;
        },
      }),
    exam: 'res12b',
  },
  {
    name: 'CM-EIP',
    file: 'notes/cmeip/CMEIP_QUESTIONS.md',
    items: CMEIP,
    render: (items, start, titles) =>
      renderHeadingStyle(items, start, {
        // `item.s` is the source tag (`CM-EIP §4.2`, `CM-EIP Appendix B`), which is
        // also what the parser reads the section number from, so it is emitted as
        // the reference and not repeated as a subtype.
        sourceRefFor: (item) => item.s,
        subtypeFor: () => null,
        groupingKey: (item) => {
          // CM-EIP assigns the chapter from the `## Chapter N — Title` heading, so
          // items are grouped under one heading per chapter, in chapter order.
          const title = titles.get(item.c) ?? item.c;
          if (/^appendix-/i.test(item.c)) {
            return `## Appendix ${item.c.split('-')[1]} — ${stripLeadingNumber(title)}`;
          }
          // The closing page is a `kind: section` guide page, not a chapter, and
          // the parser keys on its exact heading text.
          if (item.c === 'exam-method') {
            return `## ${stripLeadingNumber(title)}`;
          }
          return `## Chapter ${item.c} — ${stripLeadingNumber(title)}`;
        },
      }),
    exam: 'cmeip',
  },
];

let total = 0;
for (const job of JOBS) {
  const raw = readFileSync(job.file, 'utf8');

  // Everything above the marker is hand-written and preserved verbatim.
  const markerAt = raw.indexOf(MARKER);
  const head = markerAt === -1 ? raw.trimEnd() : raw.slice(0, markerAt).trimEnd();

  // Continue numbering from the last existing question.
  const numbers = [...head.matchAll(/^\*\*(\d+)\.\s*\[|^###\s+(\d+)\.\s*\*\*/gm)].map((m) =>
    Number(m[1] ?? m[2]),
  );
  const last = numbers.length ? Math.max(...numbers) : 0;
  const start = last + 1;

  const titles = /cmsip|fmrp|cmeip/.test(job.exam) ? guideTitles(job.exam) : new Map();
  const body = job.render(job.items, start, titles);
  const out = `${head}\n\n${MARKER}\n\n${body.trimEnd()}\n`;

  console.log(`${job.name}: ${last} existing, +${job.items.length} new -> ${start}..${start + job.items.length - 1}`);
  total += job.items.length;

  if (WRITE) writeFileSync(job.file, out, 'utf8');
}
console.log(`\n${total} extension question(s) total${WRITE ? ' — written' : ' — dry run, pass --write'}`);
