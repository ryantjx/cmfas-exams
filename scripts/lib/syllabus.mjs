/**
 * The manifest, keyed by exam id.
 * `chapters` is keyed by the guide page id (`2`, `1B-3`, …) so the audit can match
 * sections to the exact page that should carry them.
 */
export const SYLLABUS = {
  cmsip: { chapters: CMSIP_SECTIONS, appendices: SYLLABUS_APPENDICES.cmsip },
  fmrp: { chapters: FMRP_SECTIONS, appendices: SYLLABUS_APPENDICES.fmrp },
  res12b: { chapters: RES12B_SECTIONS, appendices: SYLLABUS_APPENDICES.res12b },
  cmeip: { chapters: CMEIP_SECTIONS, appendices: SYLLABUS_APPENDICES.cmeip },
};

/** Flatten a chapter's `sections` pairs into `{ number, title }` objects. */
export function sectionRows(chapter) {
  return (chapter.sections ?? []).map(([number, title]) => ({ number, title }));
}

/** Total section count per exam, used in the audit summary. */
export function sectionCount(examId) {
  const entry = SYLLABUS[examId];
  if (!entry) throw new Error(`Unknown exam id: ${examId}`);
  return Object.values(entry.chapters).reduce((sum, c) => sum + sectionRows(c).length, 0);
}
